#!/usr/bin/env node
// Bundles src/content/*.md into src/content/legalContent.generated.ts so the legal pages need no
// filesystem access at runtime (Cloudflare Workers has none). Runs before `next build` / `next dev`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CONTENT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/content");
const OUT_FILE = path.join(CONTENT_DIR, "legalContent.generated.ts");

const DOCUMENTS = {
  termsOfService: "terms-of-service.md",
  privacyPolicy: "privacy-policy.md",
  refundPolicy: "refund-policy.md",
  cookiePolicy: "cookie-policy.md",
  acceptableUsePolicy: "acceptable-use-policy.md",
};

const body = Object.entries(DOCUMENTS)
  .map(([name, file]) => `export const ${name} = ${JSON.stringify(fs.readFileSync(path.join(CONTENT_DIR, file), "utf8"))};`)
  .join("\n\n");

const output = `// Generated by scripts/generate-legal-content.mjs from src/content/*.md. Do not edit by hand.\n\n${body}\n`;
if (!fs.existsSync(OUT_FILE) || fs.readFileSync(OUT_FILE, "utf8") !== output) fs.writeFileSync(OUT_FILE, output);
